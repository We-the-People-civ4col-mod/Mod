SourceFileContainer::SourceFileContainer(std::string fileWName)
	: m_filename(fileWName)
{
}

const std::string& SourceFileContainer::getText() const
{
	return m_fileAsString;
}

void SourceFileContainer::setup()
{
	std::ifstream inFile;
	inFile.open(m_filename.c_str()); //open the input file

	std::stringstream strStream;
	strStream << inFile.rdbuf(); //read the file
	m_fileAsString = strStream.str(); //copy the file content into the string
}


